export type TranslationKey = keyof typeof translations["zh"];

interface I18nContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType | null>(null);

const STORAGE_KEY_LANG = "exam_planner_language_preference";

export function I18nProvider({ children }: { children: React.ReactNode }) {

  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY_LANG);
    return (saved === "en" || saved === "zh") ? saved : "zh";
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem(STORAGE_KEY_LANG, lang);
  };

  const t = (key: string, params?: Record<string, string | number>): string => {
    const dict = (translations[language] || translations["zh"]) as Record<string, string>;
    const fallbackDict = (translations["en"] || translations["zh"]) as Record<string, string>;
    let text = String(dict[key] ?? fallbackDict[key] ?? key ?? "");
    if (params && typeof text === "string") {
      Object.entries(params).forEach(([pKey, pVal]) => {
        text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(pVal ?? ""));
      });
    }
    return text;
  };

  return (
    <I18nContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return ctx;
}
